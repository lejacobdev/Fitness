function mirrorPoints(points) {
  return points.map(mirror);
}

/** Every drawable path, keyed exactly as the app expects. */
export function buildAnatomy() {
  const outline = splinePath(fullOutline(), { tension: 0.45 });
  const muscles = {};
  for (const [view, table] of [['front', FRONT_MUSCLES], ['back', BACK_MUSCLES]]) {
    for (const [slug, shape] of Object.entries(table)) {
      // A muscle is one closed shape, or several (e.g. the two heads of
      // the gastrocnemius) joined into one path.
      const parts = Array.isArray(shape[0][0]) ? shape : [shape];
      muscles[`${slug}.${view}.right`] = parts.map((pts) => splinePath(pts)).join(' ');
      muscles[`${slug}.${view}.left`] = parts.map((pts) => splinePath(mirrorPoints(pts).reverse())).join(' ');
    }
  }
  const details = { front: [], back: [] };
  for (const [view, lines] of [['front', FRONT_DETAILS], ['back', BACK_DETAILS]]) {
    for (const line of lines) {
      details[view].push(splinePath(line, { closed: false }));
      const mirrored = mirrorPoints(line);
      const isMidline = line.every(([x]) => Math.abs(x - MID) < 0.6);
      if (!isMidline) details[view].push(splinePath(mirrored, { closed: false }));
    }
  }
  return { outline, head: HEAD, muscles, details };
}
