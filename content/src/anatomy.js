/**
 * The anatomical mannequin behind every muscle map (§9 job 1) — drawn here
 * as data, never imported or traced art. An athletic figure in a relaxed
 * A-pose, front and back, in the same 100 x 200 canonical space as before.
 *
 * Every shape is a closed Catmull-Rom spline through a handful of authored
 * points, emitted as smooth cubic Béziers, so outlines read as organic
 * anatomy rather than rounded polygons. Only the RIGHT half (x >= 50) is
 * authored; the left is its mirror image.
 */

export const ANATOMY_WIDTH = 100;
export const ANATOMY_HEIGHT = 200;
const MID = 50;

const mirror = ([x, y]) => [2 * MID - x, y];

/** Closed (or open) Catmull-Rom spline through `points`, as an SVG path. */
export function splinePath(points, { closed = true, tension = 0.5 } = {}) {
  const n = points.length;
  if (n < 2) throw new Error('a spline needs at least two points');
  const p = (i) => (closed ? points[(i + n) % n] : points[Math.max(0, Math.min(n - 1, i))]);
  const f = (v) => Number(v.toFixed(2));
  let d = `M${f(p(0)[0])},${f(p(0)[1])}`;
  const segments = closed ? n : n - 1;
  for (let i = 0; i < segments; i += 1) {
    const p0 = p(i - 1);
    const p1 = p(i);
    const p2 = p(i + 1);
    const p3 = p(i + 2);
    const k = tension / 3;
    const c1 = [p1[0] + (p2[0] - p0[0]) * k, p1[1] + (p2[1] - p0[1]) * k];
    const c2 = [p2[0] - (p3[0] - p1[0]) * k, p2[1] - (p3[1] - p1[1]) * k];
    d += ` C${f(c1[0])},${f(c1[1])} ${f(c2[0])},${f(c2[1])} ${f(p2[0])},${f(p2[1])}`;
  }
  return closed ? `${d} Z` : d;
}

